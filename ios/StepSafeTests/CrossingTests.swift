        for yaw: Float in [0, 30] {
            XCTAssertNil(run(seconds: 5, scene: { _ in parked },
                             cam: { t in self.camera(SIMD3(0, 1.6, -1.3 * Float(t)), yawDeg: yaw) }), "yaw \(yaw)")
        }
